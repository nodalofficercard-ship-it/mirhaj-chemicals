const INDEX_RANK = new Map(INDEX_ORDER.map((slug, index) => [slug, index]));

export function productsInIndex<T extends { slug: string }>(products: T[]) {
  return [...products].sort(
    (a, b) => (INDEX_RANK.get(a.slug) ?? 999) - (INDEX_RANK.get(b.slug) ?? 999),
  );
}

